// Client brands, each generated from the same engine as the house theme.
//
// WHY THIS EXISTS.
//
// `theme.mjs` is the single source of truth for GENER8V's own palette, and it says so: hue 263,
// `matches gener8v.com's cool ink`, `blue-600, the site's action colour`. That is this firm's
// brand, and every product built on the system shares it.
//
// A client engagement is not that. Before this file, a client's product carried its navy, its
// gold and its paper as raw values in its own stylesheet, under a comment reading *a client's
// brand is the one thing the design system cannot supply* — which was true, and is the thing this
// file changes. The consuming app had to hand-roll nine neutral steps, pick the two selectors that
// scope them to light mode, and keep a guard that permits raw hexes in one block so it could.
// Every later engagement would have done the same work again, differently.
//
// The system's own rule is that something genuinely missing is added here rather than to the
// consuming app. Per-client theming was genuinely missing.
//
// WHAT A BRAND MAY SET, AND WHAT IT MAY NOT.
//
// A brand is a **palette**, never a geometry and never a component. It cannot change the space
// scale, the radii, the type scale or any class name — those are what make a GENER8V product
// recognisable as one regardless of whose colours it wears, and a brand that could move them
// would be a fork rather than a theme.
//
// The ramps are generated by `neutralRamp` and `ramp`, the same functions the house theme uses,
// so a brand's steps are the system's lightness curve in another hue rather than nine hexes
// somebody picked out of a screenshot.
//
// `pin` is the one place raw values belong, for the reason `theme.mjs` already gives about its
// own grounds: a page's ground is a decision, not a step on a ramp. It is also what keeps an ink
// near-neutral — the neutral curve drives chroma to its maximum at step 900, and a body text
// taken from there comes out tinted.

export const brands = [
  {
    // An example brand, not a real client: warm paper, a deep navy and a gold. It is the shape a
    // client palette takes — copy it, rename it and replace the values with the client's own.
    slug: 'ledger',
    name: 'Ledger (example)',

    // A finance-report palette. The neutrals sit at hue 85 and chroma 0.010–0.018 — warm where
    // the house greys are cool, at about half their chroma — because the paper underneath the
    // figures is what a palette like this most needs, and the house ramp does not supply it.
    palette: {
      hue: 85,
      neutralChroma: 0.018,
      // Ground, surface and ink, pinned.
      pin: { bg: '#FAF9F6', surface: '#F7F5F0', text: '#1A1614' },
      // The navy of the mark. A filled action wears it; text takes the darker ink, which reads
      // as near-black once it is a word rather than a field.
      action: '#023550',
      ink: '#01263C',
    },

    // Light only, and deliberately. Paper is a light-mode idea: a warm ground at 98% lightness
    // has no dark counterpart that is still paper, and inventing one would be this file deciding
    // something nobody has asked for. A brand that wants a dark ground pins one.
    dark: null,
  },
];

/** A brand by its slug, or undefined. */
export const brandOf = (slug) => brands.find((b) => b.slug === slug);
